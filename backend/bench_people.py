def transcript(person: dict) -> str:
    """Their talks as the reader and the writer are given them (shaping.transcript)."""
    him = person["bob"]["name"].upper()
    blocks = []
    for n, talk in enumerate(person["talks"], 1):
        lines = "\n".join(f"{'ЧЕЛОВЕК' if role == 'user' else him}: {text}" for role, text in talk)
        blocks.append(f"— разговор {n} —\n{lines}")
    return "\n\n".join(blocks)


def exchanges(person: dict) -> list[tuple[str, str]]:
    """Their line and his answer — pairs, as the scribe sees them (myself.exchanges)."""
    out: list[tuple[str, str]] = []
    for talk in person["talks"]:
        heard = "—"
        for role, text in talk:
            if role == "user":
                heard = text
            else:
                out.append((heard, text))
                heard = "—"
        if heard != "—":
            out.append((heard, "—"))
    return out


